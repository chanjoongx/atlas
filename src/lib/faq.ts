/**
 * The questions people actually ask about Atlas, answered once.
 *
 * Rendered on the landing page and, from the same array, emitted as FAQPage
 * structured data at build time. Keeping one source is not tidiness: search
 * engines require structured answers to match what a visitor can see on the
 * page, and two copies of an answer drift the first time one of them is
 * edited.
 *
 * Answers are written to be quotable on their own, because an answer engine
 * will lift one sentence and attribute it, and a sentence that only makes
 * sense next to the previous one comes out wrong.
 */

export interface FaqEntry {
  question: string;
  /** Plain text. No markup: this is read aloud as often as it is displayed. */
  answer: string;
}

